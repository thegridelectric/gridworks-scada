"""gwsproto ↔ sema conformance — the standing regression test.

gwsproto types/enums/property-formats are hand-written twins of sema vocabulary;
sema is the contract, and the scada's vendored snapshot (`sema_snapshot/sema`
beside gwsproto, regenerated by `scripts/regen_sema_snapshot.sh` from the
committed seed) is the oracle. This test runs the conformance sweep
(`gwsproto_sema_conformance.run`) against it and fails on ANY new drift: a
type/enum pinned off the snapshot's version, a twin whose pinned version has
no snapshot class, a twin whose serialized field names or required set differ
from the snapshot class, a canonical sample gwsproto rejects, a non-canonical
re-dump, an enum value set that differs from the snapshot's, a property format
that accepts a counterexample / rejects a valid example, or a snapshot word
with no twin.

The allowlists below are the checked-in record of KNOWN gaps. Two kinds:

- NO_WORD_* — gwsproto vocabulary with no sema word yet (legitimately
  gwsproto-only, e.g. LTN/market/admin types not modelled in sema). Adding one
  to sema means naming it in the seed and REMOVING it here; a new gwsproto-only
  word means ADDING it here (a deliberate, reviewed act). A word sema has that
  the seed does not name shows up here too: the fix is the seed, not the list.
- KNOWN_*_DRIFT / SNAPSHOT_UNMIRRORED_* — real conformance debt to burn down
  (gwsproto pinned off the snapshot, a twin that defaults a field sema requires,
  a closure word with no mirror). Fix the gwsproto side, then remove the entry.
  These are NOT acceptable long-term; the lists should shrink to empty. Each
  entry records the exact drift (versions, fields), so a listed word that
  drifts in any other way fails too.

The sets are matched EXACTLY, so the test fails both when a NEW gap appears and
when a listed gap is fixed but not removed here — keeping the record honest.

The snapshot is committed; a missing one is a failure, not a skip.
"""

