@pytest.fixture(scope="module")
def report() -> conformance.Report:
    assert conformance.snapshot_present(SNAPSHOT), (
        f"sema snapshot missing at {SNAPSHOT} (scripts/regen_sema_snapshot.sh)"
    )
    return conformance.run(SNAPSHOT)


def _names(items: list[str]) -> set[str]:
    return {i.split(":")[0].strip() for i in items}


def test_type_version_drift_only_known(report: conformance.Report) -> None:
    actual = set(report.version_drift)
    assert actual == KNOWN_TYPE_VERSION_DRIFT, (
        f"new type version drift: {sorted(actual - KNOWN_TYPE_VERSION_DRIFT)}; "
        f"fixed (remove from KNOWN list): {sorted(KNOWN_TYPE_VERSION_DRIFT - actual)}"
    )


def test_every_pinned_version_has_an_oracle(report: conformance.Report) -> None:
    assert report.no_oracle == [], (
        "no snapshot class at the twin's pinned version (seed that version): "
        + ", ".join(report.no_oracle)
    )


def test_no_shape_drift_beyond_known(report: conformance.Report) -> None:
    actual = report.shape_drift
    new = {k: v for k, v in actual.items() if KNOWN_SHAPE_DRIFT.get(k) != v}
    fixed = {k: v for k, v in KNOWN_SHAPE_DRIFT.items() if actual.get(k) != v}
    assert not new and not fixed, (
        "new or changed shape drift (fix the twin, or record the exact drift):\n"
        + "\n".join(f"  {k}: {v}" for k, v in new.items())
        + "\nfixed or changed (update the KNOWN entry):\n"
        + "\n".join(f"  {k}: {v}" for k, v in fixed.items())
    )


